"""Write the full experiment grid as a config file, and estimate its running time.

    python -m scripts.make_grid --base configs/baseline.yaml --out configs/grid.yaml \
        --estimate-from results/dev/phase2.jsonl

The estimate uses the per-call latencies measured in a previous log, scaled so that they
add up to the measured wall time of each session (calls overlap with parallel workers).
"""

from __future__ import annotations

import argparse
from collections import defaultdict
from pathlib import Path

import numpy as np
import yaml

from src.config import RunConfig, full_grid
from src.logging_utils import read_records
from src.topologies import call_kinds

SPLIT_SIZES = {"dev": 50, "test": 200}


def call_kind(m: dict) -> str:
    if m["role"] == "solver":
        return "chained" if m["sees"] else "solo"
    return m["role"]


def measured_call_costs(log: str | Path) -> dict[str, float]:
    """Effective wall seconds per LLM call, by kind of call (runs copied from another log are left out)."""
    records = [r for r in read_records(log, None) if not r.get("reused_from")]
    walls = {r["session_id"]: r["wall_s"] for r in records if r["record_type"] == "session_end"}
    latency_sum = defaultdict(float)
    for r in records:
        if r["record_type"] == "run" and r["session_id"] in walls:
            latency_sum[r["session_id"]] += sum(m["latency"] for m in r["messages"] if not m["is_faulty"])

    costs = defaultdict(list)
    for r in records:
        sid = r.get("session_id")
        if r["record_type"] != "run" or sid not in walls or not latency_sum[sid]:
            continue
        scale = walls[sid] / latency_sum[sid]
        for m in r["messages"]:
            if not m["is_faulty"]:
                costs[call_kind(m)].append(m["latency"] * scale)
    return {k: float(np.mean(v)) for k, v in costs.items()}


def estimate(grid, costs: dict[str, float]) -> dict:
    # Verifier calls are not measured yet: a verifier reads the problem and one solution,
    # like a chained solver, so we use that cost.
    costs = {**costs, "verifier": costs.get("verifier", costs["chained"])}
    per_question = sum(sum(n * costs[k] for k, n in call_kinds(e).items()) for e in grid)
    return {split: per_question * n / 3600 for split, n in SPLIT_SIZES.items()}


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--base", default="configs/baseline.yaml", help="config providing llm/seed/workers")
    p.add_argument("--out", default="configs/grid.yaml")
    p.add_argument("--estimate-from", default=None, help="results log with measured latencies")
    args = p.parse_args(argv)

    base = RunConfig.from_yaml(args.base)
    grid = full_grid(include_single=True)
    doc = {
        "name": "grid",
        "seed": base.seed,
        "workers": base.workers,
        "llm": {k: v for k, v in base.llm.to_dict().items() if k in ("base_url", "model", "temperature", "max_tokens")},
        "experiments": [e.to_dict() for e in grid],
    }
    Path(args.out).write_text("# Generated by scripts/make_grid.py\n" + yaml.safe_dump(doc, sort_keys=False))
    n_calls = sum(sum(call_kinds(e).values()) for e in grid)
    print(f"wrote {args.out}: {len(grid)} experiments, {n_calls} LLM calls per question")

    if args.estimate_from:
        costs = measured_call_costs(args.estimate_from)
        print("measured effective seconds per call: " + ", ".join(f"{k} {v:.2f}" for k, v in sorted(costs.items())))
        for split, hours in estimate(grid, costs).items():
            print(f"  {split:>4} ({SPLIT_SIZES[split]} q): ~{hours:.1f} h")


if __name__ == "__main__":
    main()
